#!/usr/bin/env python3
"""Move QICLean modules to their library layers and rewrite every reference to them.

The module map ``scripts/library_layers_module_map.txt`` has one entry per line
(module names; ``#`` starts a comment):

* ``OLD NEW``: the module ``OLD`` moves to ``NEW``
  (``QICLean.Analysis.TraceHolder QICLean.Analysis.TraceInequality.TraceHolder``);
* ``OLD NEW merge``: the declarations of ``OLD`` are appended to the module
  ``NEW`` (named as after the moves) and ``OLD`` is deleted;
* ``KEEP M``: the module ``M`` stays where it is.

Test files of ``QICLeanTest`` move by the same syntax (``QICLeanTest.X
QICLeanTest.Channel.X``). The layers and the reasons for each move are in
``docs/library_layers.md``.

In this repository (the default) the script

* moves each ``OLD`` file to ``NEW`` with ``git mv``, unless ``OLD`` is already
  gone; an entry whose two files are both missing is reported and skipped;
* appends each merged module to its target inside a ``section`` (before the
  target's own declarations when the target imported it) and adds its Mathlib
  imports to the target's header, then deletes it with ``git rm``;
* rewrites every occurrence of an old module name (``QICLean.A.B``) and of an
  old path (``QICLean/A/B.lean``, also without the suffix) in the tracked text
  files of ``QICLean/``, ``QICLeanTest/``, ``scripts/``, ``blueprint/``,
  ``docs/``, ``.github/`` and the top-level Markdown files, and removes the
  duplicate ``import`` lines this produces. Raw evidence snapshots under
  ``docs/audits/evidence/`` and the module map of the earlier
  region-vocabulary migration are records and are left as they were;
* reports the modules at the top level of a reorganized directory that the map
  does not know, such as modules added on another branch after the map was
  written; they stay where they are.

With ``--downstream ROOT`` it moves nothing and rewrites the references in the
Git-tracked text files of another repository (such as TNLean), so that its
``import QICLean.…`` lines follow the moves and merges. After a run, every
``import QICLean.…`` of a tracked Lean file other than a generated aggregator
must name a file of this checkout; the unresolved ones are listed and the exit
status is 1. Regenerate the aggregators afterwards with
``scripts/generate_import_aggregators.py``.

A reference is rewritten when it is an old module name, or an old module name
followed by a declaration name (a component starting with a lower-case letter).
The script is idempotent: no new name is an old name, and a new module in a
directory named like an old module (``QICLean.Algebra.OperatorSchmidt.Bounds``
beside the old ``QICLean.Algebra.OperatorSchmidt``) is not a reference to the
old one, so a second run changes nothing. ``--check`` changes nothing and lists
what a run would change (exit status 1 if anything).

Usage::

    python3 scripts/apply_library_layers.py [--check]
    python3 scripts/apply_library_layers.py --downstream ../TNLean [--check]
"""

from __future__ import annotations

import argparse
import graphlib
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP_PATH = ROOT / "scripts" / "library_layers_module_map.txt"
UPSTREAM_TREES = ("QICLean", "QICLeanTest", "scripts", "blueprint", "docs", ".github")
UPSTREAM_TOP_FILES = ("README.md", "CLAUDE.md", "QICLean.lean")
SKIPPED_PREFIXES = ("docs/audits/evidence/",)
TEXT_SUFFIXES = frozenset({
    ".lean", ".md", ".tex", ".py", ".txt", ".toml", ".yml", ".yaml", ".json", ".sh", ".cjs",
    ".bib", ".cfg",
})
# Files that must keep the old names: this map, and the map of an earlier one-time migration,
# whose entries record what it rewrote.
SELF_FILES = frozenset({
    "scripts/library_layers_module_map.txt", "scripts/migrate_region_vocabulary_modules.txt",
})
# Directories whose top level the map sorts completely; an unknown module there is reported.
REORGANIZED = ("Algebra", "Analysis", "Spectral", "Channel", "Kraus", "Entropy", "Probability",
               "Representation", "Topology", "QPF")
GENERATED_MARKER = "generated by scripts/generate_import_aggregators.py"

COMPONENT = r"[A-Za-z_][A-Za-z0-9_']*"
DOTTED_RE = re.compile(rf"(?<![\w.'/])QICLean(?:Test)?(?:\.{COMPONENT})+")
PATH_RE = re.compile(rf"(?<![\w./'])QICLean(?:Test)?(?:/{COMPONENT})+(?:\.lean)?")
IMPORT_RE = re.compile(
    rf"^(?:public\s+)?(?:meta\s+)?import\s+(?:all\s+)?(QICLean(?:\.{COMPONENT})*)", re.MULTILINE
)
HEADER_IMPORT = re.compile(r"^(?:public\s+)?(?:meta\s+)?import\s+(\S+)\s*$")
BLOCK_OPEN = re.compile(r"^(?:noncomputable\s+)?section(?:\s+(\S+))?\s*$|^namespace\s+(\S+)")


@dataclass
class ModuleMap:
    moves: dict[str, str] = field(default_factory=dict)
    merges: dict[str, str] = field(default_factory=dict)
    kept: set[str] = field(default_factory=set)

    @property
    def renames(self) -> dict[str, str]:
        """Every old name and the module that now holds its declarations."""
        return {**self.moves, **self.merges}


def read_map(path: Path = MAP_PATH) -> ModuleMap:
    """Read the map; reject duplicate sources, colliding targets and chains."""
    result = ModuleMap()
    seen: set[str] = set()
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        parts = raw.split("#", 1)[0].split()
        if not parts:
            continue
        if parts[0] == "KEEP" and len(parts) == 2:
            result.kept.add(parts[1])
            continue
        if len(parts) == 3 and parts[2] == "merge":
            table = result.merges
        elif len(parts) == 2:
            table = result.moves
        else:
            raise ValueError(f"{path}:{number}: expected 'OLD NEW [merge]', got {raw!r}")
        old, new = parts[0], parts[1]
        if old in seen:
            raise ValueError(f"{path}:{number}: {old} appears twice")
        seen.add(old)
        if old != new:
            table[old] = new
    targets = list(result.moves.values())
    duplicate = {t for t in targets if targets.count(t) > 1}
    if duplicate:
        raise ValueError(f"two modules are moved to {sorted(duplicate)}")
    chained = set(result.renames.values()) & set(result.renames)
    if chained:
        raise ValueError(f"new names that are also old names: {sorted(chained)}")
    return result


def rewrite_token(token: str, mapping: dict[str, str], separator: str) -> str:
    """Rewrite ``token`` if it is an old module name, or one followed by a declaration name.

    A component after the module that starts with a lower-case letter is a declaration, as in
    ``QICLean.Analysis.Entropy.vonNeumannEntropy``; one that starts with an upper-case letter
    is part of another module name, which may lie in a new directory named like an old module.
    """
    suffix = ""
    if separator == "/" and token.endswith(".lean"):
        token, suffix = token[: -len(".lean")], ".lean"
    parts = token.split(separator)
    for cut in range(len(parts), 1, -1):
        module = ".".join(parts[:cut])
        if module in mapping and (cut == len(parts) or parts[cut][:1].islower()):
            head = mapping[module].replace(".", separator)
            rest = separator.join(parts[cut:])
            return head + (separator + rest if rest else "") + suffix
    return token + suffix


def dedupe_imports(text: str, own: str | None = None) -> str:
    """Drop repeated ``import`` lines of a Lean file, and an import of the file itself."""
    seen: set[str] = set() if own is None else {f"import {own}"}
    out = []
    for line in text.split("\n"):
        key = line.strip()
        if HEADER_IMPORT.match(key):
            if key in seen:
                continue
            seen.add(key)
        out.append(line)
    return "\n".join(out)


def rewrite_text(text: str, mapping: dict[str, str], own: str | None = None) -> str:
    """Rewrite the references in ``text``; for a Lean file ``own`` is its module name."""
    new = DOTTED_RE.sub(lambda m: rewrite_token(m.group(0), mapping, "."), text)
    new = PATH_RE.sub(lambda m: rewrite_token(m.group(0), mapping, "/"), new)
    return dedupe_imports(new, own) if own is not None and new != text else new


def tracked_files(root: Path, trees: tuple[str, ...] | None) -> list[str]:
    command = ["git", "-C", str(root), "ls-files", "-z"]
    if trees is not None:
        command += ["--", *trees]
    out = subprocess.run(command, check=True, stdout=subprocess.PIPE).stdout.decode("utf-8")
    return [p for p in out.split("\0") if p]


def module_path(root: Path, module: str) -> Path:
    return root / (module.replace(".", "/") + ".lean")


def is_generated(path: Path) -> bool:
    return path.is_file() and GENERATED_MARKER in path.read_text(encoding="utf-8")


def move_modules(root: Path, moves: dict[str, str], check: bool) -> tuple[list[str], list[str]]:
    """``git mv`` every old module file that is still present; return moves and skips."""
    moved, skipped = [], []
    for old, new in sorted(moves.items()):
        source, target = module_path(root, old), module_path(root, new)
        # After the moves the generator may put an aggregator at an old path.
        if not source.exists() or is_generated(source):
            if not target.exists():
                skipped.append(f"{old}: neither the module nor its target {new} exists")
            continue
        if target.exists():
            raise FileExistsError(f"both {source} and {target} exist")
        moved.append(f"{old} -> {new}")
        if check:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "-C", str(root), "mv", str(source), str(target)], check=True)
    return moved, skipped


def split_header(text: str) -> tuple[list[str], list[str], str]:
    """Return the lines before the first import, the import lines, and the rest."""
    lines = text.split("\n")
    positions = [i for i, line in enumerate(lines) if HEADER_IMPORT.match(line.strip())]
    if not positions:
        return [], [], text
    first, last = positions[0], positions[-1]
    imports = [line.strip() for line in lines[first:last + 1] if line.strip()]
    return lines[:first], imports, "\n".join(lines[last + 1:])


def unclosed_blocks(body: str) -> list[str]:
    """The ``end`` lines that close the sections and namespaces left open by ``body``."""
    stack: list[str] = []
    for line in body.split("\n"):
        match = BLOCK_OPEN.match(line)
        if match:
            stack.append(match.group(1) or match.group(2) or "")
        elif re.match(r"^end\b", line) and stack:
            stack.pop()
    return [f"end {name}".rstrip() for name in reversed(stack)]


def merge_modules(root: Path, merges: dict[str, str], check: bool) -> tuple[list[str], list[str]]:
    """Append each merged module to its target and delete it; return merges and skips."""
    done, skipped = [], []
    # A merged module that another merged module imports is appended first.
    def imports_of(module: str) -> set[str]:
        path = module_path(root, module)
        return set(IMPORT_RE.findall(path.read_text(encoding="utf-8"))) if path.is_file() else set()
    order = graphlib.TopologicalSorter(
        {old: imports_of(old) & set(merges) for old in merges}).static_order()
    for old in order:
        target = merges[old]
        source, host = module_path(root, old), module_path(root, target)
        if not source.exists() or is_generated(source):
            continue
        if not host.exists():
            skipped.append(f"{old}: its target {target} does not exist")
            continue
        done.append(f"{old} -> {target}")
        if check:
            continue
        _, source_imports, body = split_header(source.read_text(encoding="utf-8"))
        host_leading, host_imports, host_body = split_header(host.read_text(encoding="utf-8"))
        # A source in the module system loses `public`: the host is an ordinary file.
        extra = []
        for line in source_imports:
            imported = HEADER_IMPORT.match(line).group(1)
            plain = f"import {imported}"
            if plain not in host_imports + extra:
                extra.append(plain)
        body = re.sub(r"^public section\s*$", "section", body, flags=re.MULTILINE)
        body = body.replace("@[expose] ", "").strip("\n")
        # A universe the host already declares may not be declared again.
        declared = set(re.findall(r"^universe\s+(.+?)\s*$", host_body, re.MULTILINE))
        declared = {name for line in declared for name in line.split()}
        body = re.sub(r"^universe\s+(.+?)\s*$",
                      lambda m: " ".join(["universe"] + [n for n in m.group(1).split()
                                                         if n not in declared])
                      if set(m.group(1).split()) - declared else "",
                      body, flags=re.MULTILINE)
        name = old.rsplit(".", 1)[1]
        block = "\n".join([f"section {name}", "", body, *unclosed_blocks(body), "",
                            f"end {name}"])
        own_import = f"import {old}"
        if own_import in host_imports:
            # The host imported the merged module, so the imports of that module stay needed.
            imports = [line for line in host_imports + extra if line != own_import]
        else:
            # The merged module imported only the host and modules the host imports.
            imports = host_imports + [line for line in extra
                                      if not line.startswith("import QICLean")]
        if own_import in host_imports:
            # The host used the merged module: its declarations go before the host's own,
            # after the module docstring.
            docstring = re.search(r"^/-!.*?-/\n", host_body, re.S | re.M)
            cut = docstring.end() if docstring else 0
            host_body = host_body[:cut] + "\n" + block + "\n\n" + host_body[cut:].lstrip("\n")
            appended = ""
        else:
            appended = "\n" + block + "\n"
        text = "\n".join(host_leading).rstrip("\n") + "\n"
        text += "\n".join(imports) + "\n" + host_body.rstrip("\n") + "\n" + appended
        host.write_text(text, encoding="utf-8")
        subprocess.run(["git", "-C", str(root), "rm", "-q", str(source)], check=True)
    return done, skipped


def rewrite_files(root: Path, files: list[str], mapping: dict[str, str], check: bool) -> list[str]:
    changed = []
    for name in files:
        if name in SELF_FILES or name.startswith(SKIPPED_PREFIXES):
            continue
        path = root / name
        if path.suffix not in TEXT_SUFFIXES or not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        if "QICLean" not in text or GENERATED_MARKER in text:
            continue  # the generator rewrites the aggregators
        own = name[: -len(".lean")].replace("/", ".") if name.endswith(".lean") else None
        new_text = rewrite_text(text, mapping, own)
        if new_text != text:
            changed.append(name)
            if not check:
                path.write_text(new_text, encoding="utf-8")
    return changed


def unresolved_imports(root: Path, upstream: Path) -> list[str]:
    """List the ``import QICLean.…`` lines of tracked Lean files that name no QICLean file."""
    missing = []
    for name in tracked_files(root, None):
        if not name.endswith(".lean") or name.startswith(SKIPPED_PREFIXES):
            continue
        path = root / name
        if not path.is_file() or is_generated(path):
            continue  # run scripts/generate_import_aggregators.py for the aggregators
        for match in IMPORT_RE.finditer(path.read_text(encoding="utf-8")):
            module = match.group(1)
            if not module_path(upstream, module).is_file():
                missing.append(f"{name}: import {module}")
    return missing


def unknown_modules(root: Path, table: ModuleMap) -> list[str]:
    """Modules at the top level of a reorganized directory that the map does not know."""
    known = set(table.renames.values()) | table.kept
    found = []
    for directory in REORGANIZED:
        for path in sorted((root / "QICLean" / directory).glob("*.lean")):
            module = f"QICLean.{directory}.{path.stem}"
            if module not in known and not is_generated(path):
                found.append(module)
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--downstream", type=Path, help="root of a repository importing QICLean")
    parser.add_argument("--check", action="store_true",
                        help="change nothing; list what would change")
    parser.add_argument("--map", type=Path, default=MAP_PATH, help="module map to apply")
    args = parser.parse_args()
    table = read_map(args.map)

    moved: list[str] = []
    merged: list[str] = []
    skipped: list[str] = []
    if args.downstream is not None:
        root = args.downstream.resolve()
        files = tracked_files(root, None)
    else:
        root = ROOT
        moved, skipped = move_modules(root, table.moves, args.check)
        merged, merge_skipped = merge_modules(root, table.merges, args.check)
        skipped += merge_skipped
        # Listed after the moves, so that a moved file is read at its new path.
        files = tracked_files(root, UPSTREAM_TREES) + [
            f for f in UPSTREAM_TOP_FILES if (root / f).is_file()
        ]
    changed = rewrite_files(root, sorted(set(files)), table.renames, args.check)
    verb = "would" if args.check else "did"
    print(f"{len(table.moves)} moves and {len(table.merges)} merges in the map; {verb} move "
          f"{len(moved)} modules, merge {len(merged)} and rewrite {len(changed)} files")
    for entry in skipped:
        print(f"skipped {entry}")
    if args.downstream is None:
        for module in unknown_modules(root, table):
            print(f"unknown {module}: not in the map; left where it is")
    if args.check:
        for entry in moved:
            print(f"  move {entry}")
        for entry in merged:
            print(f"  merge {entry}")
        for name in changed:
            print(f"  rewrite {name}")
        return 1 if moved or merged or changed else 0
    missing = unresolved_imports(root, ROOT)
    for entry in missing:
        print(f"unresolved {entry}")
    if missing:
        print(f"{len(missing)} imports name no module of {ROOT}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
